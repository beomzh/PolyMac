import AppKit
import PolyMacCore

/// 복사한 글자에 풀어진 한글(Finder 파일명, 일부 웹·PDF에서 복사)이 있으면 클립보드를 붙은 한글로 바꿔 넣는다.
/// 바꾸는 것은 한글 낱자 조합뿐이라 글 내용은 그대로다 (HangulNormalizer.composeHangul).
///
/// 건드리지 않는 것: 비밀번호처럼 감춘 항목, 잠깐 쓰는 항목, Finder에서 복사한 파일
/// (파일 복사를 다시 쓰면 ⌘X 잘라내기가 "Finder의 복사 한 번"을 알아보지 못한다).
@MainActor
final class ClipboardHangulFix {
    static let defaultsKey = "normalize.clipboardText"

    static var isEnabled: Bool {
        get { UserDefaults.standard.object(forKey: defaultsKey) as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: defaultsKey) }
    }

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "public.file-url",
    ]
    private static let plainTypes: Set<NSPasteboard.PasteboardType> = [.string, .init("public.utf16-plain-text"), .html]

    private let pasteboard: NSPasteboard
    private let logger: (String) -> Void
    private var timer: Timer?
    private var lastChangeCount: Int

    init(pasteboard: NSPasteboard = .general, logger: @escaping (String) -> Void = { _ in }) {
        self.pasteboard = pasteboard
        self.logger = logger
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        // 클립보드 변경 알림이 없어 번호만 비교한다 (정수 비교 1회)
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func check() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard let fixed = Self.fixedItems(pasteboard) else { return }
        // 읽는 사이 다른 앱이 새로 복사했으면 덮어쓰지 않는다
        guard pasteboard.changeCount == lastChangeCount else { return }
        pasteboard.clearContents()
        pasteboard.writeObjects(fixed)
        lastChangeCount = pasteboard.changeCount
        logger("clipboard text: joined decomposed Hangul")
    }

    /// 고친 항목들. 고칠 게 없거나 건드리면 안 되는 클립보드면 nil.
    static func fixedItems(_ pb: NSPasteboard) -> [NSPasteboardItem]? {
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: skippedTypes), let items = pb.pasteboardItems, !items.isEmpty else { return nil }
        // 고칠 글자가 있을 때만 나머지(이미지 같은 큰 데이터)를 읽어 옮긴다 — 복사할 때마다 도는 곳이라
        let needsFix = items.contains { item in
            item.types.contains { type in
                plainTypes.contains(type) && item.string(forType: type).map { HangulNormalizer.composeHangul($0) != nil } == true
            }
        }
        guard needsFix else { return nil }
        var changed = false
        let copies = items.map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if plainTypes.contains(type), let text = item.string(forType: type), let fixed = HangulNormalizer.composeHangul(text) {
                    copy.setString(fixed, forType: type)
                    changed = true
                } else if type == .rtf, let data = item.data(forType: type), let fixed = fixRTF(data) {
                    copy.setData(fixed, forType: type)
                    changed = true
                } else if let data = item.data(forType: type) {
                    copy.setData(data, forType: type)
                }
            }
            return copy
        }
        return changed ? copies : nil
    }

    /// 서식은 그대로 두고 글자만 고친다 (서식 조각마다 바꿔 넣는다)
    private static func fixRTF(_ data: Data) -> Data? {
        guard let text = try? NSMutableAttributedString(data: data, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil),
              HangulNormalizer.composeHangul(text.string) != nil
        else { return nil }
        var runs: [NSRange] = []
        text.enumerateAttributes(in: NSRange(location: 0, length: text.length)) { _, range, _ in runs.append(range) }
        for range in runs.reversed() {
            let part = (text.string as NSString).substring(with: range)
            if let fixed = HangulNormalizer.composeHangul(part) { text.replaceCharacters(in: range, with: fixed) }
        }
        return try? text.data(from: NSRange(location: 0, length: text.length), documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf])
    }
}
