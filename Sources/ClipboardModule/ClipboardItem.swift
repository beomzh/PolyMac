import Foundation
import PolyMacCore

/// 클립보드 히스토리 한 항목 — 텍스트, 이미지 또는 Finder에서 복사한 파일.
/// 이미지와 큰 텍스트(긴 로그 등), 서식(RTF)은 JSON에 넣지 않고 데이터 폴더에 따로 저장한다 (0600):
/// clipboard-images/<파일>.png, clipboard-texts/<파일>.txt, clipboard-rich/<파일>.rtf
public struct ClipboardItem: Codable, Sendable, Identifiable, Equatable {
    public var id: UUID
    /// 이미지 항목이면 빈 문자열, 큰 텍스트면 앞부분(미리보기·검색용)만
    public var text: String
    /// 큰 텍스트의 전체 내용이 들어 있는 파일 (없으면 text가 전체)
    public var textFile: String?
    /// 큰 텍스트의 전체 크기 (UTF-8 바이트)
    public var textBytes: Int?
    /// 복사할 때 앞에 있던 앱의 번들 ID. PolyMac이 복사한 OCR·경로 결과는 PolyMac의 ID.
    public var sourceApp: String?
    public var copiedAt: Date
    public var isPinned: Bool
    // 이미지 항목 (예전 기록에는 없으므로 모두 옵셔널)
    public var imageFile: String?
    public var imageWidth: Int?
    public var imageHeight: Int?
    public var imageBytes: Int?
    /// 같은 이미지를 두 번 저장하지 않기 위한 SHA-256
    public var contentHash: String?
    /// Finder에서 복사한 파일·폴더 경로 (파일 내용은 저장하지 않고 경로만). text에는 경로를 줄마다 담아 검색·미리보기에 쓴다.
    public var files: [String]?
    /// 서식 있는 텍스트(RTF) 파일. text는 같은 내용의 글자만 — 서식 없이 붙여넣을 때 쓴다
    public var richFile: String?
    /// PolyMac의 어느 기능이 복사했는지 (PasteboardOrigin.rawValue). 모르는 값은 무시 — 새 버전 기록을 열어도 깨지지 않게
    public var origin: String?

    public var isImage: Bool { imageFile != nil }
    public var isFiles: Bool { !(files ?? []).isEmpty }
    /// 앞부분만 들고 있는 큰 텍스트
    public var isLargeText: Bool { textFile != nil }
    public var isRich: Bool { richFile != nil }
    public var originKind: PasteboardOrigin? { origin.flatMap(PasteboardOrigin.init(rawValue:)) }

    /// 이 항목이 쓰는 별도 파일 (지울 때 같이 지운다)
    public var storedFiles: [String] {
        [imageFile.map { "clipboard-images/" + $0 }, textFile.map { "clipboard-texts/" + $0 }, richFile.map { "clipboard-rich/" + $0 }].compactMap { $0 }
    }

    public init(id: UUID = UUID(), text: String, sourceApp: String?, copiedAt: Date = Date(), isPinned: Bool = false) {
        self.id = id
        self.text = text
        self.sourceApp = sourceApp
        self.copiedAt = copiedAt
        self.isPinned = isPinned
    }

    public static func largeText(preview: String, file: String, bytes: Int, hash: String, sourceApp: String?) -> ClipboardItem {
        var item = ClipboardItem(text: preview, sourceApp: sourceApp)
        item.textFile = file
        item.textBytes = bytes
        item.contentHash = hash
        return item
    }

    public static func richText(_ text: String, file: String, hash: String, sourceApp: String?) -> ClipboardItem {
        var item = ClipboardItem(text: text, sourceApp: sourceApp)
        item.richFile = file
        item.contentHash = hash
        return item
    }

    public static func files(_ paths: [String], sourceApp: String?) -> ClipboardItem {
        var item = ClipboardItem(text: paths.joined(separator: "\n"), sourceApp: sourceApp)
        item.files = paths
        return item
    }

    public static func image(file: String, width: Int, height: Int, bytes: Int, hash: String, sourceApp: String?) -> ClipboardItem {
        var item = ClipboardItem(text: "", sourceApp: sourceApp)
        item.imageFile = file
        item.imageWidth = width
        item.imageHeight = height
        item.imageBytes = bytes
        item.contentHash = hash
        return item
    }
}

/// 기록하지 않을 항목 판단 규칙.
public enum ClipboardPrivacy {
    /// 비밀번호 관리자 등이 붙이는 관례 타입 (nspasteboard.org).
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public static let defaultIgnoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.bitwarden.desktop",
    ]

    /// excludedApps: 사용자가 메뉴에서 고른 "기록하지 않을 앱"
    public static func shouldIgnore(types: [String], frontmostBundleID: String?, excludedApps: Set<String> = []) -> Bool {
        if types.contains(where: ignoredTypes.contains) { return true }
        if let id = frontmostBundleID, defaultIgnoredApps.contains(id) || excludedApps.contains(id) { return true }
        return false
    }
}
