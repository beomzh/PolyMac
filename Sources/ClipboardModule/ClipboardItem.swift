import Foundation

/// 클립보드 히스토리 한 항목.
public struct ClipboardItem: Sendable, Identifiable {
    public enum Content: Sendable {
        case text(String)
        case richText(Data)
        case image(fileName: String)   // 원본은 디스크에, 메모리엔 썸네일만
        case files([URL])
    }

    /// 어디서 왔는지. PolyMac 내부 모듈이 복사한 경우 해당 캡처·기능으로 돌아갈 수 있다.
    public enum Source: Sendable {
        case app(bundleID: String?)
        case ocr(captureID: UUID)
        case capture(captureID: UUID)
        case pathCopy
    }

    public let id: UUID
    public let content: Content
    public let source: Source
    public let copiedAt: Date
    public var isPinned: Bool

    public init(id: UUID = UUID(), content: Content, source: Source, copiedAt: Date = Date(), isPinned: Bool = false) {
        self.id = id
        self.content = content
        self.source = source
        self.copiedAt = copiedAt
        self.isPinned = isPinned
    }
}

/// 기록하지 않을 항목 판단 규칙.
public enum ClipboardPrivacy {
    /// 비밀번호 관리자 등이 붙이는 관례 타입 (nspasteboard.org).
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public static let defaultIgnoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.bitwarden.desktop",
    ]

    public static func shouldIgnore(types: [String], frontmostBundleID: String?) -> Bool {
        if types.contains(where: ignoredTypes.contains) { return true }
        if let id = frontmostBundleID, defaultIgnoredApps.contains(id) { return true }
        return false
    }
}
